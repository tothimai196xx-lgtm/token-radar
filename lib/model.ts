// Token Radar — the valuation model (radar-2, comps-based).
//
// The board ranks pre-token protocols by an implied value that is derived from the
// snapshot itself, never from a hand-written list of names. The market prices the
// comps; the model only applies those prices to protocols that do not trade yet.
//
//   1. Comps. For every category, take the live-token protocols in that category
//      (they record a market cap and a TVL) and use the MEDIAN of their
//      market-cap / TVL ratios as the category's multiple. A category with fewer
//      than 3 live comps falls back to the global median across all live
//      protocols. The multiple is clamped to [0.05, 1.50] so one outlier comp
//      cannot set the price for a whole category.
//   2. Base value. base = tvl_usd x category_multiple.
//   3. Growth. growth_mult = 1 + clamp(change_7d, -60, +120) / 100 x 0.5.
//      A protocol growing fast is worth more than the same TVL standing still;
//      a shrinking one is worth less. Missing growth counts as 0.
//   4. Maturity. maturity_mult = 0.6 + min(age_days, 1095) / 1095 x 0.4.
//      Age is the days since DefiLlama first listed the protocol: the record of
//      how long it has run with no token. Unknown age counts as 365 days.
//   5. Breadth. breadth_mult = 1 + 0.03 x min(chains - 1, 5), at most 1.15.
//      A protocol live on more chains has wider distribution; a single-chain
//      protocol gets no bonus.
//   implied = max(1, round(base x growth_mult x maturity_mult x breadth_mult))
//
// What the board ranks: every slug on the snapshot's watchlist, plus the
// pre-token protocols below the watchlist floor that pass the same exclusion
// rule the watchlist itself uses — no token recorded, not a CEX, not a Bridge /
// Canonical Bridge / Liquid Staking / Liquid Restaking / Restaked BTC product,
// no versioned pool name, no whole word "wrapped" / "staked" / "staking", and
// not named after an exchange. Those exclusions matter: a wrapped or staked
// product of a token that already trades is not a launch waiting to happen.
// Live-token protocols are never ranked; they are the comps, shown beside the
// board with their market caps so the reader can check the multiples.
//
// Confidence: HIGH when the age is known, growth is reported and TVL is at
// least $100M; MEDIUM when one of those is missing; LOW when two or more are
// missing or the protocol is younger than 90 days. Risk flags name the rest:
// TVL falling more than 10% in 7 days, a single chain, an unknown listing date.

